-- Profiles Policies
CREATE POLICY "Allow public read access to profiles" ON public.profiles FOR SELECT USING (true);
CREATE POLICY "Allow users to update their own profiles" ON public.profiles FOR UPDATE USING (auth.uid() = id);

-- Shipment Policies
CREATE POLICY "Allow admins full access to shipments" ON public.shipment FOR ALL USING (
    (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'admin'
);
CREATE POLICY "Allow users to view their own shipments" ON public.shipment FOR SELECT USING (
    CUSTOMERID = (SELECT customer_id FROM public.profiles WHERE id = auth.uid())
);
CREATE POLICY "Allow users to insert their own shipments" ON public.shipment FOR INSERT WITH CHECK (
    CUSTOMERID = (SELECT customer_id FROM public.profiles WHERE id = auth.uid())
);

-- Tracking Policies
CREATE POLICY "Allow anyone to read tracking details" ON public.tracking FOR SELECT USING (true);
CREATE POLICY "Allow admins to update tracking details" ON public.tracking FOR ALL USING (
    (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'admin'
);

-- Payment Policies
CREATE POLICY "Allow admins full access to payments" ON public.payment FOR ALL USING (
    (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'admin'
);
CREATE POLICY "Allow users to view their own payments" ON public.payment FOR SELECT USING (
    SHIPMENTID IN (
        SELECT SHIPMENTID FROM public.shipment
        WHERE CUSTOMERID = (SELECT customer_id FROM public.profiles WHERE id = auth.uid())
    )
);

-- Customer Policies
CREATE POLICY "Allow admins full access to customers" ON public.customer FOR ALL USING (
    (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'admin'
);
CREATE POLICY "Allow users to view/update their own customer profiles" ON public.customer FOR ALL USING (
    CUSTOMERID = (SELECT customer_id FROM public.profiles WHERE id = auth.uid())
);
