-- 4. SIGNUP TRIGGER FUNCTION (Automatic customer/profile creation)
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
    new_customer_id INT;
    user_fullname VARCHAR(100);
    user_role VARCHAR(20) := 'user';
BEGIN
    -- Determine role (the first user is promoted to admin for convenience, or check metadata)
    IF NOT EXISTS (SELECT 1 FROM public.profiles) THEN
        user_role := 'admin';
    END IF;

    -- Extract full name from user metadata, fallback to email name if not present
    user_fullname := COALESCE(new.raw_user_meta_data->>'full_name', SPLIT_PART(new.email, '@', 1));

    -- Insert into customer table
    INSERT INTO public.customer (NAME, EMAIL, REGISTRATIONDATE, STATUS)
    VALUES (user_fullname, new.email, CURRENT_DATE, 'Active')
    RETURNING CUSTOMERID INTO new_customer_id;

    -- Insert into profiles table
    INSERT INTO public.profiles (id, email, role, customer_id)
    VALUES (new.id, new.email, user_role, new_customer_id);

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger to execute handle_new_user on auth.users insert
CREATE OR REPLACE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();


-- 5. SHIPMENT TRANSACTION FUNCTION (RPC)
CREATE OR REPLACE FUNCTION public.create_shipment_with_receiver(
    p_customer_id INT,
    p_sender_street VARCHAR(100),
    p_sender_pincode INT,
    p_sender_city VARCHAR(50),
    p_sender_state VARCHAR(50),
    p_receiver_name VARCHAR(100),
    p_receiver_email VARCHAR(100),
    p_receiver_street VARCHAR(100),
    p_receiver_pincode INT,
    p_receiver_city VARCHAR(50),
    p_receiver_state VARCHAR(50),
    p_service_type_id INT,
    p_priority VARCHAR(20)
)
RETURNS INT AS $$
DECLARE
    v_receiver_id INT;
    v_base_rate DECIMAL(10,2);
    v_priority_multiplier DECIMAL(3,2) := 1.0;
    v_total_cost DECIMAL(10,2);
    v_shipment_id INT;
    v_booking_date TIMESTAMP WITH TIME ZONE := NOW();
BEGIN
    -- 1. Insert/Update Sender Pincode
    IF p_sender_pincode IS NOT NULL THEN
        INSERT INTO public.customer_pincode (PINCODE, CITY, STATE)
        VALUES (p_sender_pincode, COALESCE(p_sender_city, 'Unknown'), COALESCE(p_sender_state, 'Unknown'))
        ON CONFLICT (PINCODE) DO UPDATE
        SET CITY = CASE WHEN EXCLUDED.CITY <> 'Unknown' THEN EXCLUDED.CITY ELSE customer_pincode.CITY END,
            STATE = CASE WHEN EXCLUDED.STATE <> 'Unknown' THEN EXCLUDED.STATE ELSE customer_pincode.STATE END;

        -- Update customer's address
        UPDATE public.customer
        SET STREET = p_sender_street, PINCODE = p_sender_pincode
        WHERE CUSTOMERID = p_customer_id;
    END IF;

    -- 2. Insert/Update Receiver Pincode
    IF p_receiver_pincode IS NOT NULL THEN
        INSERT INTO public.receiver_pincode (PINCODE, CITY, STATE)
        VALUES (p_receiver_pincode, COALESCE(p_receiver_city, 'Unknown'), COALESCE(p_receiver_state, 'Unknown'))
        ON CONFLICT (PINCODE) DO NOTHING;
    END IF;

    -- 3. Match or Create Receiver
    SELECT RECEIVERID INTO v_receiver_id FROM public.receiver WHERE EMAIL = p_receiver_email LIMIT 1;
    IF v_receiver_id IS NOT NULL THEN
        UPDATE public.receiver
        SET STREET = p_receiver_street, PINCODE = p_receiver_pincode
        WHERE RECEIVERID = v_receiver_id;
    ELSE
        INSERT INTO public.receiver (NAME, EMAIL, STREET, PINCODE)
        VALUES (p_receiver_name, p_receiver_email, p_receiver_street, p_receiver_pincode)
        RETURNING RECEIVERID INTO v_receiver_id;
    END IF;

    -- 4. Get service type details
    SELECT BASERATE INTO v_base_rate
    FROM public.service_type WHERE SERVICETYPEID = p_service_type_id;
    IF v_base_rate IS NULL THEN
        v_base_rate := 50.00;
    END IF;

    -- 5. Priority cost calculation
    IF p_priority = 'High' THEN
        v_priority_multiplier := 1.5;
    ELSIF p_priority = 'Urgent' THEN
        v_priority_multiplier := 2.0;
    END IF;
    v_total_cost := v_base_rate * v_priority_multiplier;

    -- 6. Insert shipment
    INSERT INTO public.shipment (BOOKINGDATE, CURRENTSTATUS, PRIORITY, TOTALCOST, CUSTOMERID, RECEIVERID)
    VALUES (v_booking_date, 'Booked', p_priority, v_total_cost, p_customer_id, v_receiver_id)
    RETURNING SHIPMENTID INTO v_shipment_id;

    -- 7. Insert initial tracking history
    INSERT INTO public.tracking (SHIPMENTID, STATUS, LOCATION, TIMESTAMP)
    VALUES (v_shipment_id, 'Booked', COALESCE(p_sender_city, 'Origin') || ' Warehouse', v_booking_date);

    -- 8. Insert initial payment record
    INSERT INTO public.payment (SHIPMENTID, PAYMENTSTATUS, PAYMENTDATE, PAYMENTMETHOD, TRANSACTIONID)
    VALUES (v_shipment_id, 'Pending', v_booking_date::DATE, 'Not Set', 'TXN' || v_shipment_id || FLOOR(RANDOM() * 9000 + 1000)::TEXT);

    RETURN v_shipment_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


