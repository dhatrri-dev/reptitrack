-- 2. CREATE TABLES

CREATE TABLE public.courier (
    COURIERID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(100),
    PHONE VARCHAR(20)
);

CREATE TABLE public.customer_pincode (
    PINCODE INT PRIMARY KEY,
    CITY VARCHAR(50),
    STATE VARCHAR(50)
);

CREATE TABLE public.customer (
    CUSTOMERID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(100),
    EMAIL VARCHAR(100) UNIQUE,
    REGISTRATIONDATE DATE,
    STATUS VARCHAR(20),
    STREET VARCHAR(100),
    PINCODE INT REFERENCES public.customer_pincode(PINCODE) ON DELETE SET NULL
);

CREATE TABLE public.receiver_pincode (
    PINCODE INT PRIMARY KEY,
    CITY VARCHAR(50),
    STATE VARCHAR(50)
);

CREATE TABLE public.receiver (
    RECEIVERID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(100),
    EMAIL VARCHAR(100) UNIQUE,
    STREET VARCHAR(100),
    PINCODE INT REFERENCES public.receiver_pincode(PINCODE) ON DELETE SET NULL
);

CREATE TABLE public.service_type (
    SERVICETYPEID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SERVICENAME VARCHAR(50),
    DELIVERYDAYS INT,
    BASERATE DECIMAL(10,2)
);

CREATE TABLE public.shipment (
    SHIPMENTID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BOOKINGDATE TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    CURRENTSTATUS VARCHAR(30) DEFAULT 'Booked',
    PRIORITY VARCHAR(20) DEFAULT 'Normal',
    TOTALCOST DECIMAL(10,2) DEFAULT 0.00,
    CUSTOMERID INT REFERENCES public.customer(CUSTOMERID) ON DELETE CASCADE,
    RECEIVERID INT REFERENCES public.receiver(RECEIVERID) ON DELETE SET NULL,
    COURIERID INT REFERENCES public.courier(COURIERID) ON DELETE SET NULL
);

CREATE TABLE public.tracking (
    TRACKINGID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STATUS VARCHAR(30) DEFAULT 'Booked',
    LOCATION VARCHAR(100),
    TIMESTAMP TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    SHIPMENTID INT REFERENCES public.shipment(SHIPMENTID) ON DELETE CASCADE
);

CREATE TABLE public.payment (
    PAYMENTID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PAYMENTDATE DATE,
    PAYMENTMETHOD VARCHAR(30) DEFAULT 'Not Set',
    PAYMENTSTATUS VARCHAR(20) DEFAULT 'Pending',
    TRANSACTIONID VARCHAR(50),
    SHIPMENTID INT REFERENCES public.shipment(SHIPMENTID) ON DELETE CASCADE
);

-- User Profiles to map authenticated users to their customer profiles and roles
CREATE TABLE public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email VARCHAR(255) UNIQUE NOT NULL,
    role VARCHAR(20) DEFAULT 'user',
    customer_id INT REFERENCES public.customer(CUSTOMERID) ON DELETE SET NULL
);

